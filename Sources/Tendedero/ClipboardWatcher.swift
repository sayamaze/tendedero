import AppKit

/// Hangs images and text copied to the clipboard, like a screenshot taken
/// with Control held or a paragraph copied anywhere. Images are saved as PNG
/// and text as UTF-8 .txt in Tendedero's own folder, so on the line they
/// behave like any screenshot.
///
/// Off until the user turns it on. The pasteboard has no change notification,
/// so its change count is checked twice a second; what was copied is only read
/// once its types say it is a picture or plain text and nothing else.
@MainActor
final class ClipboardWatcher {
    private let onItem: (URL) -> Void
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    /// The last image saved. Some apps put the same image on the clipboard
    /// again; it hangs once, unless it has been taken down since.
    private var last: (png: Data, url: URL)?
    /// The last text saved, same idea. Plain copies in a row of the same
    /// paragraph are one entry on the line, not a pile.
    private var lastText: (string: String, url: URL)?

    private static let enabledKey = "clipboardEnabled"

    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    /// Copies that carry a picture but are not one. A file copied in Finder
    /// brings its icon, and a photo copied from the line brings its file.
    /// Password managers and similar apps mark private or temporary copies,
    /// following nspasteboard.org. Text is checked separately: it must be
    /// the only content, or a copy from a text editor would be skipped just
    /// because the app also offers an image of the selection.
    private static let imageIgnoredTypes: Set<NSPasteboard.PasteboardType> = [
        .string, .fileURL,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// A text copy is hung by its plain text. Many editors (MOSS, Notes,
    /// browsers) put the same text out in several flavours at once — utf8,
    /// utf16, styled wrappers, legacy Mac types — so extra string-like types
    /// must not disqualify it. Only these do: a real file or link, a real
    /// image (a screenshot also offers its bitmap, and the bitmap wins), and
    /// private or transient copies. Rich text (rtf/html) is hung as its plain
    /// text rather than skipped.
    private static let textIgnoredTypes: Set<NSPasteboard.PasteboardType> = [
        .fileURL, .URL,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Whether any item carries an actual image, which then wins over text.
    private static func hasImage(_ items: [NSPasteboardItem]) -> Bool {
        let bitmaps: Set<NSPasteboard.PasteboardType> = [
            .png, .tiff, .init("public.jpeg"), .init("public.png"), .init("public.tiff"),
        ]
        return items.contains { !bitmaps.isDisjoint(with: $0.types) }
    }

    /// Anything bigger is not a screenshot.
    private static let maxBytes = 64 * 1024 * 1024
    nonisolated private static let maxPixels = 80_000_000
    /// A whole document pasted by accident is not a note. Longer text still
    /// reaches the clipboard as usual; it just does not hang.
    private static let maxTextCharacters = 20_000

    init(onItem: @escaping (URL) -> Void) {
        self.onItem = onItem
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already is old news.
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard let items = pb.pasteboardItems, !items.isEmpty else { return }
        // An image-only copy wins: a screenshot with Control held offers both
        // the picture and its file, and the picture is the interesting part.
        if items.allSatisfy({ Self.imageIgnoredTypes.isDisjoint(with: $0.types) }),
           let type = pb.availableType(from: [.png, .tiff]),
           let data = pb.data(forType: type), data.count <= Self.maxBytes,
           pb.changeCount == count {
            // Decoding a large image takes a moment, so it happens off the main thread.
            DispatchQueue.global(qos: .userInitiated).async { [weak self] in
                let png = ClipboardWatcher.png(from: data, type: type)
                DispatchQueue.main.async {
                    // Copied over again in the meantime: that copy is the one that counts.
                    guard let png, NSPasteboard.general.changeCount == count else { return }
                    self?.save(png)
                }
            }
            return
        }
        // Text is hung unless a file, link or private copy says no, and an
        // actual image always wins over its accompanying text.
        guard items.allSatisfy({ Self.textIgnoredTypes.isDisjoint(with: $0.types) }),
              !Self.hasImage(items),
              pb.changeCount == count else { return }
        // A copy whose data has not landed yet reads as an empty string;
        // those are left alone rather than hung as blank notes.
        guard let text = pb.string(forType: .string), !text.isEmpty else { return }
        save(text)
    }

    /// PNG bytes are kept as they are; TIFF becomes PNG. Either way the image
    /// must decode and have a sane size.
    nonisolated private static func png(from data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard let rep = NSBitmapImageRep(data: data),
              rep.pixelsWide > 0, rep.pixelsHigh > 0,
              rep.pixelsWide <= maxPixels / rep.pixelsHigh else { return nil }
        return type == .png ? data : rep.representation(using: .png, properties: [:])
    }

    private func save(_ png: Data) {
        if let last, last.png == png, FileManager.default.fileExists(atPath: last.url.path) { return }
        guard let url = write(png, named: "Clipboard \(Self.stamp())", extension: "png") else { return }
        last = (png, url)
        onItem(url)
    }

    private func save(_ text: String) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, text.count <= Self.maxTextCharacters else { return }
        if let lastText, lastText.string == text,
           FileManager.default.fileExists(atPath: lastText.url.path) { return }
        guard let data = text.data(using: .utf8),
              let url = write(data, named: "Clipboard \(Self.stamp())", extension: "txt") else { return }
        lastText = (text, url)
        onItem(url)
    }

    /// The one write both kinds share. What people copy can be private: only
    /// they can read it.
    private func write(_ data: Data, named name: String, extension ext: String) -> URL? {
        let fm = FileManager.default
        var url = Inbox.folder.appendingPathComponent(name).appendingPathExtension(ext)
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = Inbox.folder.appendingPathComponent("\(name) \(n)").appendingPathExtension(ext)
            n += 1
        }
        do {
            try fm.createDirectory(at: Inbox.folder, withIntermediateDirectories: true)
            try data.write(to: url, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            return url
        } catch {
            try? fm.removeItem(at: url)
            log.error("Could not save a clipboard item: \(error.localizedDescription, privacy: .public)")
            return nil
        }
    }

    private static func stamp() -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        return f.string(from: Date())
    }
}
